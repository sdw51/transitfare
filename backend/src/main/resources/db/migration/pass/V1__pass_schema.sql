create table ticket_product (
    code                varchar(64)   primary key,
    region_code         varchar(32)   not null,
    type                varchar(16)   not null,
    name_ja             varchar(200)  not null,
    name_ko             varchar(200)  not null,
    price               integer       not null,        -- 어른 1명 가격
    valid_days          integer       not null,        -- PASS: 사용 일수 / FIXED_ROUTE: 첫 사용일부터 유효 일수
    consecutive_days    boolean       not null,
    uses                integer       not null,        -- FIXED_ROUTE 승차 횟수 (PASS는 0 = 무제한)
    covers_express      boolean       not null,
    reserved_seat_limit integer       not null,        -- 지정석 커버 횟수 (0이면 커버 안 함)
    eligibility_note    varchar(500),
    source_url          varchar(1000) not null,
    verified_on         date          not null,
    constraint ck_ticket_product_type check (type in ('PASS', 'FIXED_ROUTE'))
);
create index ix_ticket_product_region on ticket_product (region_code);

create table ticket_coverage (
    id            bigint generated by default as identity primary key,
    product_code  varchar(64) not null references ticket_product (code),
    operator_code varchar(64) not null,
    line_id       bigint,       -- null: 운영사 전 노선
    station_a_id  bigint,       -- FIXED_ROUTE의 양 끝 역 (방향 무관)
    station_b_id  bigint
);
create index ix_ticket_coverage_product on ticket_coverage (product_code);
