-- transit 모듈 스키마. 금액은 지역 통화의 정수 최소 단위, 어른 1명 기준(어린이 요금은 다루지 않음).
-- id는 100000부터 자동 생성. 시드(V100~)는 id를 넣지 않고 이름으로 서브쿼리 참조.

create table region (
    code     varchar(32)  primary key,
    name_ko  varchar(100) not null,
    name_ja  varchar(100) not null,
    currency varchar(3)   not null,
    timezone varchar(64)  not null
);

create table operator (
    code            varchar(64)  primary key,
    region_code     varchar(32)  not null references region (code),
    name_ja         varchar(100) not null,
    name_ko         varchar(100) not null,
    fare_rule_type  varchar(32)  not null,
    fare_basis_note varchar(500),
    constraint ck_operator_fare_rule_type
        check (fare_rule_type in ('DISTANCE_BAND', 'STATION_PAIR', 'FLAT_ZONE_PLUS_PAIR', 'MANUAL_ONLY'))
);

create table operator_alias (
    id            bigint generated by default as identity (start with 100000) primary key,
    operator_code varchar(64)  not null references operator (code),
    alias         varchar(200) not null,
    constraint uq_operator_alias unique (operator_code, alias)
);

create table line (
    id            bigint generated by default as identity (start with 100000) primary key,
    operator_code varchar(64)  not null references operator (code),
    code          varchar(64)  not null,
    name_ja       varchar(100) not null,
    name_ko       varchar(100) not null,
    constraint uq_line_code unique (operator_code, code)
);

-- 같은 실제 역도 운영사별로 별도 행
create table station (
    id            bigint generated by default as identity (start with 100000) primary key,
    region_code   varchar(32)  not null references region (code),
    operator_code varchar(64)  not null references operator (code),
    name_ja       varchar(100) not null,
    name_ko       varchar(100),
    source_url    varchar(500) not null,
    verified_on   date         not null,
    constraint uq_station_name unique (operator_code, name_ja)
);

create table line_station (
    line_id       bigint        not null references line (id),
    station_id    bigint        not null references station (id),
    cumulative_km numeric(6, 1) not null,
    primary key (line_id, station_id)
);

create table station_alias (
    id         bigint generated by default as identity (start with 100000) primary key,
    station_id bigint       not null references station (id),
    alias      varchar(200) not null,
    constraint uq_station_alias unique (station_id, alias)
);

create table distance_fare_band (
    id            bigint generated by default as identity (start with 100000) primary key,
    operator_code varchar(64)   not null references operator (code),
    kind          varchar(16)   not null,
    max_km        numeric(6, 1) not null,
    amount        integer       not null,
    source_url    varchar(500)  not null,
    verified_on   date          not null,
    constraint ck_distance_fare_band_kind check (kind in ('BASE', 'EXPRESS')),
    constraint uq_distance_fare_band unique (operator_code, kind, max_km)
);

-- 양방향 동일 요금. (a, b)와 (b, a) 중 하나만 넣는다.
create table pair_fare (
    id            bigint generated by default as identity (start with 100000) primary key,
    operator_code varchar(64)  not null references operator (code),
    station_a_id  bigint       not null references station (id),
    station_b_id  bigint       not null references station (id),
    kind          varchar(16)  not null,
    amount        integer      not null,
    source_url    varchar(500) not null,
    verified_on   date         not null,
    constraint ck_pair_fare_kind check (kind in ('BASE', 'EXPRESS')),
    constraint uq_pair_fare unique (operator_code, kind, station_a_id, station_b_id)
);

create table flat_zone (
    id            bigint generated by default as identity (start with 100000) primary key,
    operator_code varchar(64)  not null references operator (code),
    amount        integer      not null,
    source_url    varchar(500) not null,
    verified_on   date         not null
);

create table flat_zone_station (
    zone_id    bigint not null references flat_zone (id),
    station_id bigint not null references station (id),
    primary key (zone_id, station_id)
);

create table reserved_seat_fee (
    id            bigint generated by default as identity (start with 100000) primary key,
    operator_code varchar(64)  not null references operator (code),
    amount        integer      not null,
    source_url    varchar(500) not null,
    verified_on   date         not null,
    constraint uq_reserved_seat_fee unique (operator_code)
);

create table transfer_discount (
    id                 bigint generated by default as identity (start with 100000) primary key,
    from_operator_code varchar(64)  not null references operator (code),
    to_operator_code   varchar(64)  not null references operator (code),
    discount           integer      not null,
    note               varchar(500),
    source_url         varchar(500) not null,
    verified_on        date         not null,
    constraint uq_transfer_discount unique (from_operator_code, to_operator_code)
);
